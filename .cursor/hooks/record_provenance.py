#!/usr/bin/env python3
"""Cursor hook sink: record event metadata and hashes, never raw prompts or text."""
import hashlib
import json
import os
import sys
import uuid
from datetime import datetime, timezone
from pathlib import Path

ZERO = "0" * 64
ROOT = Path(os.environ.get("CURSOR_PROJECT_DIR") or Path.cwd()).resolve()
STORE = ROOT / ".writing-provenance"
LOG = STORE / "cursor-events.jsonl"


def sha(value):
    if isinstance(value, str):
        value = value.encode("utf-8", errors="replace")
    return hashlib.sha256(value).hexdigest()


def relative_file(raw):
    if not isinstance(raw, str) or not raw:
        return None
    try:
        p = Path(raw).resolve()
        return str(p.relative_to(ROOT))
    except (ValueError, OSError):
        return "[outside-workspace]"


def event_payload(data):
    name = data.get("hook_event_name", "unknown")
    out = {
        "event_type": "cursor_" + name,
        "evidence_class": "editor_or_ai_tool_observed",
        "source": "Cursor hook",
    }
    # Keep identifiers useful for correlation, but do not persist prompts, responses,
    # edit text, shell commands, tool arguments, transcripts, or reasoning.
    for key in ("session_id", "conversation_id", "generation_id", "tool_use_id", "cursor_version", "model", "model_id"):
        value = data.get(key)
        if isinstance(value, (str, int, float, bool)):
            out[key] = value
    if name in ("beforeSubmitPrompt",):
        prompt = data.get("prompt")
        if isinstance(prompt, str):
            out["prompt_sha256"] = sha(prompt)
            out["prompt_character_count"] = len(prompt)
        attachments = data.get("attachments")
        if isinstance(attachments, list):
            out["attachment_count"] = len(attachments)
    if name in ("afterAgentResponse",):
        response = data.get("text")
        if isinstance(response, str):
            out["response_sha256"] = sha(response)
            out["response_character_count"] = len(response)
    if name in ("afterFileEdit", "afterTabFileEdit"):
        out["path"] = relative_file(data.get("file_path"))
        edits = data.get("edits")
        if isinstance(edits, list):
            out["edit_count"] = len(edits)
            summaries = []
            for edit in edits:
                if not isinstance(edit, dict):
                    continue
                old = edit.get("old_string", edit.get("old_line", ""))
                new = edit.get("new_string", edit.get("new_line", ""))
                summaries.append({
                    "old_text_sha256": sha(old) if isinstance(old, str) else None,
                    "new_text_sha256": sha(new) if isinstance(new, str) else None,
                    "old_character_count": len(old) if isinstance(old, str) else None,
                    "new_character_count": len(new) if isinstance(new, str) else None,
                })
            out["edits"] = summaries
    if name in ("sessionStart", "sessionEnd"):
        for key in ("reason", "duration_ms", "is_background_agent", "composer_mode", "final_status", "status"):
            value = data.get(key)
            if isinstance(value, (str, int, float, bool)):
                out[key] = value
    if name == "stop":
        for key in ("status", "loop_count"):
            value = data.get(key)
            if isinstance(value, (str, int, float, bool)):
                out[key] = value
    out["interpretation"] = (
        "Cursor emitted this hook event. It is evidence of a tool/editor event, "
        "not proof that every changed character was generated by AI or authored by a particular person."
    )
    return out


def append(record):
    STORE.mkdir(mode=0o700, parents=True, exist_ok=True)
    try:
        os.chmod(STORE, 0o700)
    except OSError:
        pass
    previous = ZERO
    if LOG.exists():
        with LOG.open("r", encoding="utf-8") as f:
            for line in f:
                if line.strip():
                    try:
                        previous = json.loads(line).get("event_hash", ZERO)
                    except json.JSONDecodeError:
                        previous = "INVALID_LOG"
    event = {
        "schema": "writing-provenance/v1",
        "observed_at_utc": datetime.now(timezone.utc).isoformat(),
        "event_id": str(uuid.uuid4()),
        **record,
        "previous_event_hash": previous,
    }
    encoded = json.dumps(event, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    event["event_hash"] = sha(encoded)
    with LOG.open("a", encoding="utf-8") as f:
        f.write(json.dumps(event, ensure_ascii=False, sort_keys=True, separators=(",", ":")) + "\n")
    try:
        os.chmod(LOG, 0o600)
    except OSError:
        pass


def main():
    try:
        data = json.load(sys.stdin)
        if not isinstance(data, dict):
            return 0
        append(event_payload(data))
    except Exception as exc:
        # Do not echo input content to logs or stderr; avoid leaking prompt/file text.
        print("writing-provenance hook error: " + type(exc).__name__, file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
